def _pool(champ, po):
    """우승확률·가을야구확률(0~1) → 상황 버킷 리스트."""
    if champ >= 0.20:
        return _WIN_STRONG
    if champ >= 0.08:
        return _WIN_RACE
    if po >= 0.60:
        return _FALL_LIKELY
    if po >= 0.35:
        return _FALL_RACE
    if po >= 0.05:
        return _HARD
    return _OUT


def team_line(champ, po):
    """'💬 ...' 한 줄(상황 버킷에서 랜덤)."""
    return "💬 " + random.choice(_pool(champ, po))


